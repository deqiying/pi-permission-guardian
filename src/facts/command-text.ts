/**
 * 调用级文本的规范化（FR-62）。
 *
 * 该文本用于**跨命令单元的模式匹配**（`curl * | sh`），不参与单元级匹配，
 * 因此可以比单元文本做更多改写：单元文本必须保持"能看出实际执行了什么"，
 * 而这里只要求"同一段代码在不同书写风格下得到同一个字符串"。
 */

/** 需要在两侧补空格的 shell 操作符；长操作符排在前面，避免 `||` 被拆成两个 `|`。 */
const OPERATORS = /\s*(\|\||&&|\|&|;;|\||;)\s*/g;

/**
 * 规范化一段命令文本：折叠空白（含换行与行继续）、统一操作符两侧空格。
 *
 * 目的是让 `curl a|sh`、`curl a | sh`、`curl a |\n  sh` 三种写法得到同一个字符串，
 * 否则配置里写 `curl * | sh` 只能命中其中一种。
 *
 * 已知副作用：引号内的操作符也会被补空格（`echo "a|b"` → `echo "a | b"`）。
 * 这只影响调用级文本；单元文本保持原样，因此不会改变"实际执行了什么"的判断。
 */
export function normalizeCommandText(text: string): string {
  return text
    .replace(OPERATORS, " $1 ")
    .replace(/\s+/g, " ")
    .trim();
}
